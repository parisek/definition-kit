<?php

declare(strict_types=1);

namespace Parisek\DefinitionKit\Generator\Sdc;

/**
 * Prototype: a component definition to a Drupal Single Directory Component
 * metadata array (`<name>.component.yml`).
 *
 * Each definition field becomes a prop (a JSON Schema) or, for `richtext`, a
 * slot. The rules are in {@see self::propSchema()}. The result is a plain
 * array: the caller writes it as YAML.
 *
 * The shapes of `media` and `link` follow the formatting layer of the stack
 * (`schemas/type-return-shapes.yaml`), because the component template reads
 * those keys. A field the definition cannot describe closely (`reference`,
 * `flexible_content`, `open: true`) becomes a loose schema, and the generator
 * records it in {@see self::$notes} so that the report says what is loose.
 */
final class SdcComponentGenerator
{
    public const SCHEMA_URL = 'https://git.drupalcode.org/project/drupal/-/raw/HEAD/core/assets/schemas/v1/metadata.schema.json';

    /** Media types as the formatting layer returns them, one value. */
    private const MEDIA_ITEM = [
        'type' => 'object',
        'properties' => [
            // The formatting layer leaves a key null when the media has no value.
            'src' => ['type' => ['string', 'null']],
            'type' => ['type' => ['string', 'null']],
            'alt' => ['type' => ['string', 'null']],
            'width' => ['type' => ['integer', 'null']],
            'height' => ['type' => ['integer', 'null']],
        ],
    ];

    private const LINK = [
        'type' => 'object',
        'properties' => [
            'url' => ['type' => 'string'],
            'title' => ['type' => 'string'],
            'target' => ['type' => 'string'],
        ],
    ];

    /** @var string[] what was loose or skipped, as "path: reason" */
    public array $notes = [];

    /**
     * @param array<string,mixed> $definition the parsed `<name>.yaml`
     * @return array<string,mixed> the `component.yml` content
     */
    public function generate(array $definition, string $name): array
    {
        $this->notes = [];
        $properties = [];
        $required = [];
        $slots = [];

        foreach ((array) ($definition['fields'] ?? []) as $key => $field) {
            if (!is_string($key) || !is_array($field)) {
                continue;
            }
            self::assertKey($key);
            if (($field['role'] ?? 'field') === 'inherited') {
                continue;
            }
            if (($field['type'] ?? '') === 'richtext') {
                $slots[$key] = $this->described(['title' => (string) ($field['label'] ?? $key)], $field);
                continue;
            }
            $properties[$key] = $this->propSchema($field, $key);
            if (($field['required'] ?? false) === true) {
                $required[] = $key;
            }
        }

        $meta = [
            '$schema' => self::SCHEMA_URL,
            'name' => (string) ($definition['name'] ?? $name),
            'status' => 'experimental',
        ];
        if (isset($definition['description']) && '' !== $definition['description']) {
            $meta['description'] = (string) $definition['description'];
        }
        if (isset($definition['category'])) {
            $meta['group'] = (string) $definition['category'];
        }
        $meta['props'] = ['type' => 'object', 'properties' => $properties] + ([] !== $required ? ['required' => $required] : []);
        if ([] === $properties) {
            $meta['props'] = ['type' => 'object', 'properties' => new \stdClass()];
        }
        if ([] !== $slots) {
            $meta['slots'] = $slots;
        }

        return $meta;
    }

    /**
     * The template of the generated component. It maps the props and slots back
     * to the `content` variable that the component template reads, and includes
     * that template. The SDC is then a typed front for the existing template.
     *
     * @param array<string,mixed> $meta the result of generate()
     */
    public function wrapperTwig(array $meta, string $name, string $namespace = 'component'): string
    {
        $keys = array_merge(
            array_keys((array) ($meta['props']['properties'] ?? [])),
            array_keys((array) ($meta['slots'] ?? [])),
        );
        $slots = array_keys((array) ($meta['slots'] ?? []));
        // A slot arrives as a render array. The template runs string filters on
        // it (`|typography`), so the wrapper renders it to markup first.
        $lines = array_map(
            static fn (string $key): string => in_array($key, $slots, true)
                ? "  '{$key}': {$key} is empty ? null : {$key}|render,"
                : "  '{$key}': {$key}|default(null),",
            $keys,
        );

        return "{# Generated by fields-generate-sdc from {$name}.yaml. Do not edit. #}\n"
            . "{% set content = {\n" . implode("\n", $lines) . "\n} %}\n"
            . "{% include '@{$namespace}/{$name}/{$name}.twig' with { content: content } %}\n";
    }

    /**
     * A key becomes a Twig variable name and a prop name. Refuse any other
     * shape: `my-field` reads as a subtraction in Twig and a quote breaks the
     * template.
     */
    private static function assertKey(string $key): void
    {
        if (1 !== preg_match('/^[a-zA-Z_][a-zA-Z0-9_]*$/', $key)) {
            throw new \InvalidArgumentException("field key '{$key}' is not a valid Twig variable name");
        }
    }

    /**
     * @param array<string,mixed> $field
     * @return array<string,mixed>
     */
    private function propSchema(array $field, string $path): array
    {
        $type = (string) ($field['type'] ?? '');
        $multiple = ($field['multiple'] ?? false) === true;

        $schema = match ($type) {
            // Older definitions use `textarea`, `email`, `phone` and `url` as types.
            'text', 'textarea', 'phone' => $this->text($field),
            'email' => $this->text($field) + ['format' => 'email'],
            'url' => ['type' => 'string', 'format' => 'uri-reference'],
            'number' => $this->number($field),
            'boolean' => ['type' => 'boolean'],
            'select' => $this->select($field),
            'media' => $this->media($field, $multiple),
            'link' => 'url' === ($field['shape'] ?? null) ? ['type' => 'string'] : self::LINK,
            'date' => ['type' => 'string', 'format' => 'date-time'],
            'object' => $this->object($field, $path),
            'list' => ['type' => 'array', 'items' => $this->object($field, $path)],
            'reference' => $this->loose($path, 'reference: the value depends on the CMS'),
            'flexible_content' => ['type' => 'array', 'items' => $this->loose($path, 'flexible_content: layouts are not described')],
            default => $this->loose($path, "type '{$type}' has no SDC rule"),
        };

        if ($multiple && !in_array($type, ['media', 'list', 'flexible_content'], true)) {
            $schema = ['type' => 'array', 'items' => $schema];
        } elseif (is_scalar($field['default'] ?? null) && in_array($type, ['text', 'textarea', 'number', 'boolean', 'select'], true)) {
            $schema['default'] = $field['default'];
        }

        return $this->described($schema, $field);
    }

    /**
     * @param array<string,mixed> $field
     * @return array<string,mixed>
     */
    private function text(array $field): array
    {
        $schema = ['type' => 'string'];
        if (isset($field['maxlength']) && is_int($field['maxlength'])) {
            $schema['maxLength'] = $field['maxlength'];
        }

        return $schema;
    }

    /**
     * @param array<string,mixed> $field
     * @return array<string,mixed>
     */
    private function number(array $field): array
    {
        $schema = ['type' => 'number'];
        foreach (['min' => 'minimum', 'max' => 'maximum'] as $from => $to) {
            if (isset($field[$from]) && is_numeric($field[$from])) {
                $schema[$to] = $field[$from] + 0;
            }
        }

        return $schema;
    }

    /**
     * @param array<string,mixed> $field
     * @return array<string,mixed>
     */
    private function select(array $field): array
    {
        $options = is_array($field['options'] ?? null) ? $field['options'] : [];
        if ([] === $options) {
            return ['type' => 'string'];
        }
        // Options are a map (value => label) or a list of {value, label} items
        // or of plain values.
        $labels = [];
        foreach ($options as $key => $option) {
            if (is_array($option)) {
                $value = $option['value'] ?? $option['key'] ?? null;
                if (!is_scalar($value)) {
                    continue;
                }
                $labels[(string) $value] = (string) (is_scalar($option['label'] ?? null) ? $option['label'] : $value);
            } elseif (is_int($key) && array_is_list($options)) {
                $labels[(string) $option] = (string) $option;
            } else {
                $labels[(string) $key] = (string) $option;
            }
        }
        if ([] === $labels) {
            return ['type' => 'string'];
        }
        $schema = ['type' => 'string', 'enum' => array_map('strval', array_keys($labels))];
        $schema['meta:enum'] = $labels;

        return $schema;
    }

    /**
     * @param array<string,mixed> $field
     * @return array<string,mixed>
     */
    private function media(array $field, bool $multiple): array
    {
        // The formatting layer returns a list, also for one image
        // (picture.md: "the image itself is an array"). Every media field is a
        // list of items.
        $list = ['type' => 'array', 'items' => self::MEDIA_ITEM];

        // A gallery is a list of images, and each image is itself a list.
        return 'gallery' === ($field['kind'] ?? null) ? ['type' => 'array', 'items' => $list] : $list;
    }

    /**
     * @param array<string,mixed> $field
     * @return array<string,mixed>
     */
    private function object(array $field, string $path): array
    {
        if (($field['open'] ?? false) === true) {
            return ['type' => 'object', 'additionalProperties' => true];
        }
        if (isset($field['of']) && is_string($field['of']) && !isset($field['fields'])) {
            return $this->loose($path, "of: {$field['of']} borrows a shape the generator does not resolve");
        }
        $properties = [];
        $required = [];
        foreach ((array) ($field['fields'] ?? []) as $key => $child) {
            if (!is_string($key) || !is_array($child)) {
                continue;
            }
            self::assertKey($key);
            if (($child['type'] ?? '') === 'richtext') {
                // A slot cannot sit inside an object. It stays a string.
                $properties[$key] = $this->described(['type' => 'string'], $child);
                $this->notes[] = "{$path}.{$key}: richtext inside an object is a string, not a slot";
                continue;
            }
            $properties[$key] = $this->propSchema($child, "{$path}.{$key}");
            if (($child['required'] ?? false) === true) {
                $required[] = $key;
            }
        }
        $schema = ['type' => 'object', 'properties' => [] === $properties ? new \stdClass() : $properties];
        if ([] !== $required) {
            $schema['required'] = $required;
        }

        return $schema;
    }

    /**
     * @return array<string,mixed>
     */
    private function loose(string $path, string $why): array
    {
        $this->notes[] = "{$path}: {$why}";

        // Core SDC refuses a prop with no `type`, so "any value" lists them all.
        return [
            'type' => ['string', 'number', 'boolean', 'object', 'array', 'null'],
            'description' => "Loose schema: {$why}.",
        ];
    }

    /**
     * Adds the label and description.
     *
     * @param array<string,mixed> $schema
     * @param array<string,mixed> $field
     * @return array<string,mixed>
     */
    private function described(array $schema, array $field): array
    {
        if (isset($field['label']) && '' !== $field['label'] && !isset($schema['title'])) {
            $schema = ['title' => (string) $field['label']] + $schema;
        }
        if (isset($field['description']) && '' !== $field['description']) {
            $schema['description'] = (string) $field['description'];
        }

        return $schema;
    }
}
